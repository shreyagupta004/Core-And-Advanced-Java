public class lec_13_operatorAndOperand {
    public static void main(String args[]){
        int num=13;
        //num=num+10;
        num+=10;
        System.out.println(num);

        //num=num-10;
        num-=10;
        System.out.println(num);

        //num=num*10;
        num*=10;
        System.out.println(num);

        //num=num/10;
        num/=10;
        System.out.println(num);

        //num=num%2;
        num%=2;
        System.out.println(num);

        num++;
        System.out.println(num);

        num--;
        System.out.println(num);
    }
}
